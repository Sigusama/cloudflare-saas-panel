CREATE TABLE IF NOT EXISTS dns_operations (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 zone_ref BIGINT UNSIGNED NOT NULL,
 record_id VARCHAR(64) NOT NULL,
 hostname VARCHAR(253) NOT NULL,
 action VARCHAR(20) NOT NULL,
 actor VARCHAR(100) NOT NULL,
 before_json MEDIUMTEXT NOT NULL,
 after_json MEDIUMTEXT NULL,
 options_json MEDIUMTEXT NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'queued',
 write_planned TINYINT NOT NULL DEFAULT 0,
 domain_id BIGINT UNSIGNED NULL,
 job_id BIGINT UNSIGNED NULL,
 attempts INT NOT NULL DEFAULT 0,
 last_error TEXT NULL,
 run_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX pending(status,run_at),
 INDEX zone_record(zone_ref,record_id,id),
 FOREIGN KEY (zone_ref) REFERENCES zones(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
