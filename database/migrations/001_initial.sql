CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(100) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS settings (
 name VARCHAR(100) PRIMARY KEY,
 value TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS accounts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 provider VARCHAR(30) NOT NULL DEFAULT 'cloudflare',
 token_encrypted TEXT NOT NULL,
 active TINYINT NOT NULL DEFAULT 1,
 checked_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS zones (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 account_id BIGINT UNSIGNED NOT NULL,
 cf_id VARCHAR(64) NOT NULL,
 name VARCHAR(253) NOT NULL,
 status VARCHAR(30) NOT NULL,
 UNIQUE KEY account_zone(account_id,cf_id),
 FOREIGN KEY (account_id) REFERENCES accounts(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS profiles (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 account_id BIGINT UNSIGNED NOT NULL,
 zone_id VARCHAR(64) NOT NULL,
 zone_name VARCHAR(253) NOT NULL,
 cname_target VARCHAR(253) NOT NULL,
 fallback_origin VARCHAR(253) NOT NULL,
 active TINYINT NOT NULL DEFAULT 1,
 FOREIGN KEY (account_id) REFERENCES accounts(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS entries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 kind VARCHAR(20) NOT NULL,
 targets TEXT NOT NULL,
 active TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS origins (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 profile_id BIGINT UNSIGNED NOT NULL,
 mode VARCHAR(20) NOT NULL,
 hostname VARCHAR(253) NULL,
 active TINYINT NOT NULL DEFAULT 1,
 FOREIGN KEY (profile_id) REFERENCES profiles(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS domains (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 hostname VARCHAR(253) NOT NULL UNIQUE,
 profile_id BIGINT UNSIGNED NOT NULL,
 dns_account_id BIGINT UNSIGNED NOT NULL,
 dns_zone_id VARCHAR(64) NOT NULL,
 entry_id BIGINT UNSIGNED NOT NULL,
 origin_id BIGINT UNSIGNED NOT NULL,
 replace_existing TINYINT NOT NULL DEFAULT 0,
 status VARCHAR(40) NOT NULL DEFAULT 'queued',
 cf_hostname_id VARCHAR(64) NULL,
 hostname_created TINYINT NOT NULL DEFAULT 0,
 hostname_status VARCHAR(50) NOT NULL DEFAULT 'pending',
 ssl_status VARCHAR(50) NOT NULL DEFAULT 'pending',
 cleanup_status VARCHAR(40) NOT NULL DEFAULT 'pending',
 remote_json MEDIUMTEXT NULL,
 diagnostic_json TEXT NULL,
 last_error TEXT NULL,
 next_check_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (profile_id) REFERENCES profiles(id),
 FOREIGN KEY (dns_account_id) REFERENCES accounts(id),
 FOREIGN KEY (entry_id) REFERENCES entries(id),
 FOREIGN KEY (origin_id) REFERENCES origins(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS jobs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 domain_id BIGINT UNSIGNED NOT NULL,
 kind VARCHAR(30) NOT NULL DEFAULT 'onboard',
 stage VARCHAR(40) NOT NULL DEFAULT 'precheck',
 status VARCHAR(40) NOT NULL DEFAULT 'queued',
 attempts INT NOT NULL DEFAULT 0,
 checks INT NOT NULL DEFAULT 0,
 context_json MEDIUMTEXT NULL,
 last_error TEXT NULL,
 run_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY runnable(status,run_at),
 FOREIGN KEY (domain_id) REFERENCES domains(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS verification_records (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 domain_id BIGINT UNSIGNED NOT NULL,
 purpose VARCHAR(30) NOT NULL,
 name VARCHAR(253) NOT NULL,
 value TEXT NOT NULL,
 fingerprint CHAR(64) NOT NULL,
 zone_id VARCHAR(64) NOT NULL,
 record_id VARCHAR(64) NOT NULL,
 owned TINYINT NOT NULL,
 status VARCHAR(40) NOT NULL DEFAULT 'present',
 UNIQUE KEY verification(domain_id,fingerprint),
 FOREIGN KEY (domain_id) REFERENCES domains(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS dns_changes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 domain_id BIGINT UNSIGNED NOT NULL,
 job_id BIGINT UNSIGNED NOT NULL,
 account_id BIGINT UNSIGNED NOT NULL,
 zone_id VARCHAR(64) NOT NULL,
 record_id VARCHAR(64) NULL,
 action VARCHAR(20) NOT NULL,
 purpose VARCHAR(30) NOT NULL,
 before_json TEXT NULL,
 after_json TEXT NULL,
 state VARCHAR(30) NOT NULL DEFAULT 'planned',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (domain_id) REFERENCES domains(id),
 FOREIGN KEY (job_id) REFERENCES jobs(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 actor VARCHAR(100) NOT NULL,
 domain_id BIGINT UNSIGNED NULL,
 job_id BIGINT UNSIGNED NULL,
 event VARCHAR(100) NOT NULL,
 message TEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 KEY domain_logs(domain_id,id),
 KEY job_logs(job_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS api_tokens (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE,
 scopes TEXT NOT NULL,
 expires_at DATETIME NULL,
 revoked_at DATETIME NULL,
 last_used_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS api_rate_limits (
 bucket VARCHAR(190) PRIMARY KEY,
 hits INT NOT NULL,
 expires_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS idempotency_requests (
 owner VARCHAR(80) NOT NULL,
 request_key VARCHAR(128) NOT NULL,
 fingerprint CHAR(64) NOT NULL,
 response_json MEDIUMTEXT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(owner,request_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
